"""【概要】スクリプトで決め打ちした「つかむ動作」の定義。

動画を出力するデモ(demo_grasp.py)とGUI(view_grasp.py)の両方がこの動作を使う。
動作は「目標姿勢のリスト」で、各目標へ一定時間かけて直線的に移っていく。
"""
import numpy as np

# 指令値の並び順は scene.xml の <actuator> の順と同じ:
#   [手のひらの上下, 左基節, 左先節, 右基節, 右先節]
# 手のひらの値は「初期位置からのずれ[m]」(マイナスで下がる)、指の値は角度[rad]。
OPEN = np.array([-0.0, -0.1, -0.1, 0.1, 0.1])   # 指を開いた姿勢
DOWN = OPEN.copy(); DOWN[0] = -0.115             # 手のひらを下げた姿勢(物体の高さまで)
# .copy() は必須: 付けないと DOWN を変えたとき OPEN も一緒に変わってしまう。
# ; は1行に複数の文を書く記法。[頻度] あまり使わない(ここでは短く書くために使用)。

# 指先でつまむ姿勢。掃引(値を変えて試す)で決めた値。曲げが大きいと物体を掬い上げてしまう。
CLOSE = DOWN.copy(); CLOSE[1:] = [-0.3, -0.2, 0.3, 0.2]  # [1:] は「2番目以降」
LIFT = CLOSE.copy(); LIFT[0] = -0.02             # 手のひらを上げた姿勢

# (目標姿勢, かける時間[秒]) のリスト。上から順に実行する。
PHASES = [(OPEN, 0.5), (DOWN, 1.0), (CLOSE, 0.1), (LIFT, 1.5)]
# 物体の高さ(z)がこの値[m]を超えたら「持ち上げ成功」とみなす。
SUCCESS_Z = 0.08


def ctrl_at(t):
    """時刻 t[秒] での指令値を返す。各目標の間は直線的に補間し、最後の目標は保持する。"""
    prev, start = OPEN, 0.0          # prev: 今の区間の出発姿勢, start: 区間の開始時刻
    for goal, dur in PHASES:         # (goal, dur) = タプルを2つに分けて受け取る書き方。[頻度] 定番
        if t < start + dur:          # 時刻tが、この区間の中にあるなら
            # 線形補間: 出発 + (目標-出発) × 進み具合(0〜1)
            return prev + (goal - prev) * (t - start) / dur
        prev, start = goal, start + dur   # 次の区間へ進む(2つの代入を同時に行う書き方。[頻度] 定番)
    return prev                      # 全区間を過ぎたら最後の姿勢のまま
